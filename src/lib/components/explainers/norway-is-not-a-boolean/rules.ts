import type { TokenRule } from '../formats/tokenise';

/* All inner groups are non-capturing so token indices stay aligned. */
export const RULES: Record<string, TokenRule[]> = {
	json:[
		[/\/\/[^\n]*/, "com"],
		[/"(?:[^"\\]|\\.)*"(?=\s*:)/, "key"],
		[/"(?:[^"\\]|\\.)*"/, "str"],
		[/'(?:[^'\\]|\\.)*'(?=\s*:)/, "key"],
		[/'(?:[^'\\]|\\.)*'/, "str"],
		[/(?:^|(?<=[{,\s]))[A-Za-z_$][\w$]*(?=\s*:)/, "key"],
		[/\b(?:true|false|null|NaN)\b|[+-]?Infinity/, "lit"],
		[/[+-]?0[xX][0-9a-fA-F]+|[+-]?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?/, "num"],
		[/[{}\[\],:]/, "pun"]
	],
	yaml:[
		[/#[^\n]*/, "com"],
		[/^\s*-?\s*[\w.\-\/]+(?=\s*:)/, "key"],
		[/"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'/, "str"],
		[/\b\d{4}-\d{2}-\d{2}(?:T[\d:.]+Z?)?/, "num"],
		[/\b(?:true|false|null|yes|no|on|off)\b/, "lit"],
		[/(?<=[:\s\[,])[+-]?\d+(?:\.\d+)?\b/, "num"],
		[/[|>&*\[\]{},]/, "pun"]
	],
	toml:[
		[/#[^\n]*/, "com"],
		[/^\s*\[\[?[^\]]+\]\]?/, "lit"],
		[/^\s*[\w.\-"]+(?=\s*=)/, "key"],
		[/"""|"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'/, "str"],
		[/\b\d{4}-\d{2}-\d{2}(?:T[\d:.]+Z?)?/, "num"],
		[/\b(?:true|false)\b/, "lit"],
		[/(?<=[=\s\[,])[+-]?\d+(?:\.\d+)?\b/, "num"],
		[/[=\[\],]/, "pun"]
	],
	env:[
		[/#[^\n]*/, "com"],
		[/^[A-Za-z_][A-Za-z0-9_]*(?==)/, "key"],
		[/"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'/, "str"],
		[/=/, "pun"]
	],
	turtle:[
		[/#[^\n]*/, "com"],
		[/@[a-z]+/, "lit"],
		[/<[^>\s]*>/, "lit"],
		[/"(?:[^"\\]|\\.)*"/, "str"],
		[/\^\^/, "pun"],
		[/\ba\b(?=\s)/, "lit"],
		[/[A-Za-z][\w.\-]*:[\w.\-]*/, "key"],
		[/(?<=\s)[+-]?\d+(?:\.\d+)?\b/, "num"],
		[/[;,.]/, "pun"]
	],
	xml:[
		[/<!--[\s\S]*?-->/, "com"],
		[/"(?:[^"\\]|\\.)*"/, "str"],
		[/<\/?[A-Za-z][\w.\-]*|\/?>/, "tag"],
		[/[A-Za-z_][\w.\-]*(?==)/, "att"],
		[/=/, "pun"]
	],
	csv:[
		[/"(?:[^"]|"")*"?/, "str"],
		[/\b\d{4}-\d{2}-\d{2}(?:T[\d:.]+Z?)?/, "num"],
		[/(?<=^|,)\d+(?:\.\d+)?(?=,|$)/, "num"],
		[/,/, "pun"]
	]
};
