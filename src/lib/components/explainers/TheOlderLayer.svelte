{#snippet maniFollows()}
	<p>
		<strong>Refutation requires accurate quotation, or the refutation misses.</strong> An opponent
		who paraphrases loosely can be told he is attacking something nobody believes, which is fatal
		to the argument. The incentive runs towards getting it right.
	</p>
	<p>
		That is a claim you would want to test rather than assume, and it was testable. Manuscript
		finds in Egypt and along the Silk Road during the twentieth century finally supplied
		Manichaean texts directly, which allowed the hostile summaries to be checked against the real
		thing.
	</p>
