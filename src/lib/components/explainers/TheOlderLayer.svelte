{#snippet gaulGet()}
	<p>
		<strong>Those are not their names, and Caesar knew it.</strong> He is translating, in the
		ordinary Roman way, by identifying a foreign god with whichever domestic one does the same
		job.
	</p>
	<p>
		So the account tells us what functions Gaulish gods were thought to perform, expressed in the
		categories of a different pantheon, and loses almost every name they were actually called by.
		Where inscriptions have since supplied real Gaulish names, they do not map onto his list
		neatly.
	</p>
	<p>The information is real. It has simply been passed through a grid that was not built for it, and the grid is now inseparable from the data.</p>
{/snippet}

